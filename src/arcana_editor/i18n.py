def load_language() -> str:
    global _language
    try:
        _language = json.loads(_CONFIG.read_text(encoding="utf-8")).get("language", ENGLISH)
    except (OSError, ValueError):
        _language = ENGLISH
    return _language


def set_language(language: str) -> None:
    global _language
    _language = language
    try:
        _CONFIG.write_text(json.dumps({"language": language}), encoding="utf-8")
    except OSError:
        pass


